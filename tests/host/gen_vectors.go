// Test vector generator for the host tests (#17).
//
// Runs freedo's own Go code (the reference the C port follows) on synthetic
// inputs and prints tests/host/vectors_freedo.h. Run it through
// tests/host/gen-vectors.sh, which starts it inside the freedo module so
// that the import below resolves. Nothing here comes from a capture: keys
// and addresses are made up, so the output is safe to commit.
package main

import (
	"fmt"
	"math/rand"
	"net/netip"
	"os"
	"strings"

	"freedo/tado"
)

var out strings.Builder
var blobs int

func hexArr(b []byte) string {
	var s strings.Builder
	s.WriteString("{")
	for i, x := range b {
		if i%16 == 0 {
			s.WriteString("\n    ")
		}
		fmt.Fprintf(&s, "0x%02x,", x)
	}
	if len(b) == 0 {
		s.WriteString("0")
	}
	s.WriteString("\n}")
	return s.String()
}

// blob emits one byte array and returns "{name, len}".
func blob(b []byte) string {
	blobs++
	name := fmt.Sprintf("vb%d", blobs)
	n := len(b)
	if n == 0 {
		n = 1
	}
	fmt.Fprintf(&out, "static const uint8_t %s[%d] = %s;\n", name, n, hexArr(b))
	return fmt.Sprintf("{%s, %d}", name, len(b))
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen_vectors:", err)
		os.Exit(1)
	}
}

func rnd(r *rand.Rand, n int) []byte {
	b := make([]byte, n)
	r.Read(b)
	return b
}

// eui returns a made-up wire address: 5 random bytes and the fixed tail.
func eui(r *rand.Rand) []byte {
	return append(rnd(r, 5), 0xc5, 0x1b, 0x00)
}

func iidStr(a tado.IPHCAddr) string {
	if a.IID == nil {
		return "0, {0}"
	}
	var s []string
	for _, x := range a.IID {
		s = append(s, fmt.Sprintf("0x%02x", x))
	}
	return "1, {" + strings.Join(s, ", ") + "}"
}

func main() {
	r := rand.New(rand.NewSource(17))
	key := rnd(r, 16)
	key2 := rnd(r, 16)

	fmt.Fprintf(&out, "/* Generated by tests/host/gen_vectors.go from freedo's Go code. Do not edit.\n")
	fmt.Fprintf(&out, " * Regenerate with tests/host/gen-vectors.sh. Synthetic keys and addresses. */\n")
	fmt.Fprintf(&out, "#ifndef VECTORS_FREEDO_H\n#define VECTORS_FREEDO_H\n\n")
	fmt.Fprintf(&out, "struct vblob { const uint8_t *p; size_t n; };\n\n")
	keyB := blob(key)
	key2B := blob(key2)
	fmt.Fprintf(&out, "static const struct vblob v_key = %s;\nstatic const struct vblob v_key2 = %s;\n\n", keyB, key2B)

	// Wake-up frames.
	var rows []string
	for i := 0; i < 8; i++ {
		seq := byte(r.Intn(256))
		dst := rnd(r, 2)
		if i == 0 {
			dst = []byte{0xff, 0xff}
		}
		rendez := uint16(r.Intn(65536))
		if i == 1 {
			rendez = 0
		}
		f := tado.BuildWakeUp(seq, dst, rendez)
		rows = append(rows, fmt.Sprintf("    {0x%02x, {0x%02x, 0x%02x}, %d, %s},", seq, dst[0], dst[1], rendez, blob(f)))
	}
	fmt.Fprintf(&out, "static const struct { uint8_t seq; uint8_t dst[2]; uint16_t rendezvous; struct vblob frame; } v_wake[] = {\n%s\n};\n\n", strings.Join(rows, "\n"))

	// Enhanced ACKs, and the Data frame headers they answer.
	rows = nil
	for i := 0; i < 8; i++ {
		seq := byte(r.Intn(256))
		own, peer := eui(r), eui(r)
		phase := uint16(r.Intn(65536))
		if i < 2 {
			phase = 0
		}
		ack := tado.BuildEnhAck(seq, peer, own, phase)
		a, err := tado.ParseEnhAck(ack)
		must(err)
		if a.CSLPhase != phase {
			must(fmt.Errorf("phase round trip"))
		}
		// The uplink this ACK answers: peer -> own, same seq.
		up, err := tado.BuildData(key, seq, own, peer[:5], tado.WrapAppPayload(rnd(r, 20), 7, nil))
		must(err)
		rows = append(rows, fmt.Sprintf("    {0x%02x, %s, %s, %d, %s, %s},", seq, blob(peer), blob(own), phase, blob(ack), blob(up.Bytes()[:16])))
	}
	fmt.Fprintf(&out, "static const struct { uint8_t seq; struct vblob peer, own; uint16_t phase; struct vblob ack, data_hdr; } v_ack[] = {\n%s\n};\n\n", strings.Join(rows, "\n"))

	// Unicast Data frames.
	rows = nil
	for i, n := range []int{0, 1, 15, 16, 17, 40, 96, 97} {
		seq := byte(r.Intn(256))
		dst, src := eui(r), eui(r)
		ctr := r.Uint32()
		dgram := rnd(r, n)
		pending := i%2 == 1
		build := tado.BuildData
		if pending {
			build = tado.BuildDataPending
		}
		f, err := build(key, seq, dst, src[:5], tado.WrapAppPayload(dgram, ctr, nil))
		must(err)
		p, err := tado.ParseData(key, f.Bytes())
		must(err)
		if len(p.Plaintext) != 8+n+2 {
			must(fmt.Errorf("plaintext length"))
		}
		pb := 0
		if pending {
			pb = 1
		}
		rows = append(rows, fmt.Sprintf("    {%d, 0x%02x, %s, %s, 0x%08xu, %s, %s},", pb, seq, blob(dst), blob(src), ctr, blob(dgram), blob(f.Bytes())))
	}
	fmt.Fprintf(&out, "static const struct { int pending; uint8_t seq; struct vblob dst, src; uint32_t counter; struct vblob dgram, frame; } v_data[] = {\n%s\n};\n\n", strings.Join(rows, "\n"))

	// Broadcast Data frames.
	rows = nil
	for i, n := range []int{0, 4, 33, 76, 103} {
		seq := byte(r.Intn(256))
		src := eui(r)
		ctr := r.Uint32()
		pkt := rnd(r, n)
		pending := i%2 == 1
		build := tado.BuildBroadcast
		if pending {
			build = tado.BuildBroadcastPending
		}
		f, err := build(key2, seq, src, uint16(ctr), 0x04, tado.WrapBroadcastPayload(pkt, uint16(ctr>>16)))
		must(err)
		pb := 0
		if pending {
			pb = 1
		}
		rows = append(rows, fmt.Sprintf("    {%d, 0x%02x, %s, 0x%08xu, %s, %s},", pb, seq, blob(src), ctr, blob(pkt), blob(f)))
	}
	fmt.Fprintf(&out, "static const struct { int pending; uint8_t seq; struct vblob src; uint32_t counter; struct vblob pkt, frame; } v_bcast[] = {\n%s\n};\n\n", strings.Join(rows, "\n"))

	// Enhanced Beacon: a third user of the sealed-frame shape (pairing, #19).
	rows = nil
	for i := 0; i < 2; i++ {
		f, err := tado.BuildEnhancedBeacon(key2, byte(r.Intn(256)), eui(r), eui(r), r.Uint32())
		must(err)
		rows = append(rows, fmt.Sprintf("    {%s},", blob(f)))
	}
	fmt.Fprintf(&out, "static const struct { struct vblob frame; } v_beacon[] = {\n%s\n};\n\n", strings.Join(rows, "\n"))

	// 6LoWPAN datagrams: link-local with and without checksum, context 0,
	// and the relayed form; with what freedo's parser reads from each.
	type dg struct {
		pkt      []byte
		src, dst []byte // L2 wire addresses of the frame that carries it
	}
	var dgs []dg
	coapMsg := func(n int) tado.CoAPReq {
		return tado.CoAPReq{Type: "CON", Code: "0.03", MID: uint16(r.Intn(65536)), Token: rnd(r, 1+r.Intn(8)),
			Path: []string{"z", "s"}, Query: []string{"id=3"}, Payload: rnd(r, n)}
	}
	for _, n := range []int{0, 1, 30, 60} {
		q := coapMsg(n)
		q.SrcEUI, q.DstEUI = eui(r), eui(r)
		q.SrcPort, q.DstPort = 4005, 5683
		p, err := tado.BuildCoAP(q)
		must(err)
		dgs = append(dgs, dg{p, q.SrcEUI, q.DstEUI})
	}
	{
		q := coapMsg(12)
		q.SrcEUI, q.DstEUI = eui(r), eui(r)
		q.ElideChecksum = true
		p, err := tado.BuildCoAP(q)
		must(err)
		dgs = append(dgs, dg{p, q.SrcEUI, q.DstEUI})
		q = coapMsg(20)
		q.SrcEUI, q.DstEUI = eui(r), eui(r)
		p, err = tado.BuildContextCoAP(q)
		must(err)
		dgs = append(dgs, dg{p, q.SrcEUI, q.DstEUI})
		inner, err := tado.ParseCoAP(append(append([]byte{}, p...), 0, 0))
		must(err)
		via, dst := eui(r), eui(r)
		p, err = tado.BuildZoneRelay(inner.Raw, rnd(r, 8), dst, 5683, 5683)
		must(err)
		dgs = append(dgs, dg{p, via, dst})
	}
	rows = nil
	for _, d := range dgs {
		m, err := tado.ParseCoAP(append(append([]byte{}, d.pkt...), 0, 0))
		must(err)
		linkLocal, ck, okck := 0, uint16(0), 0
		if m.LinkLocal() {
			linkLocal = 1
		}
		if c, ok := m.RecomputeChecksum(d.src, d.dst); ok {
			ck, okck = c, 1
		}
		rows = append(rows, fmt.Sprintf("    {%s, %s, %s, %d, %s, %d, %s, %d, %d, %d, 0x%04x, 0x%04x, %d, %s},",
			blob(d.pkt), blob(d.src), blob(d.dst), m.Src.Ctx, iidStr(m.Src), m.Dst.Ctx, iidStr(m.Dst), m.SrcPort, m.DstPort,
			linkLocal, m.Checksum, ck, okck, blob(m.Raw)))
	}
	fmt.Fprintf(&out, "static const struct { struct vblob pkt, l2src, l2dst; int src_ctx; int src_has_iid; uint8_t src_iid[8]; int dst_ctx; int dst_has_iid; uint8_t dst_iid[8]; uint16_t sport, dport; int link_local; uint16_t cksum_inline, cksum_calc; int cksum_ok; struct vblob coap; } v_dgram[] = {\n%s\n};\n\n", strings.Join(rows, "\n"))

	// Fragmentation: FRAG1/FRAGN bodies of link-local datagrams, and the
	// message freedo's reassembler returns from the frames that carry them.
	fmt.Fprintf(&out, "struct vfrag { struct vblob pkt, src, dst; uint16_t tag; unsigned count; struct vblob body[16]; struct vblob frame[16]; struct vblob coap; };\n")
	rows = nil
	for _, n := range []int{73, 74, 150, 153, 154, 400, 1205} {
		q := coapMsg(n)
		q.SrcEUI, q.DstEUI = eui(r), eui(r)
		p, err := tado.BuildCoAP(q)
		must(err)
		if len(p) <= 97 {
			must(fmt.Errorf("%d bytes fit one Data frame; freedo's callers do not fragment that", len(p)))
		}
		tag := uint16(r.Intn(65536))
		bodies, err := tado.Fragment6LoWPANDatagram(p, tag)
		must(err)
		ra := tado.NewReassembler()
		var bs, fs []string
		var got *tado.CoAPMessage
		for i, b := range bodies {
			f, err := tado.BuildDataPending(key, byte(i), q.DstEUI, q.SrcEUI[:5], tado.WrapAppPayload(b, uint32(100+i), nil))
			must(err)
			pf, err := tado.ParseData(key, f.Bytes())
			must(err)
			if m, ok := ra.Add(pf); ok {
				got = m
			}
			bs = append(bs, blob(b))
			fs = append(fs, blob(f.Bytes()))
		}
		if got == nil {
			must(fmt.Errorf("freedo did not reassemble %d bytes", n))
		}
		rows = append(rows, fmt.Sprintf("    {%s, %s, %s, 0x%04x, %d, {%s}, {%s}, %s},", blob(p), blob(q.SrcEUI), blob(q.DstEUI), tag, len(bodies),
			strings.Join(bs, ", "), strings.Join(fs, ", "), blob(got.Raw)))
	}
	fmt.Fprintf(&out, "static const struct vfrag v_frag[] = {\n%s\n};\n\n", strings.Join(rows, "\n"))

	// Sizes that must not be fragmented (they fit one Data frame).
	q := coapMsg(10)
	q.SrcEUI, q.DstEUI = eui(r), eui(r)
	p, err := tado.BuildCoAP(q)
	must(err)
	if _, err := tado.Fragment6LoWPANDatagram(p, 1); err == nil {
		must(fmt.Errorf("freedo fragmented a datagram that fits one frame"))
	}

	// Router Advertisement as the bridge broadcasts it.
	{
		src := eui(r)
		ra := tado.BridgeRouterAdvert(src, mustAddr("192.168.1.1"), mustAddr("192.168.1.1"))
		pkt, err := tado.BuildRouterAdvert(src, ra)
		must(err)
		fmt.Fprintf(&out, "static const struct { struct vblob src, pkt; } v_ra = {%s, %s};\n\n", blob(src), blob(pkt))
	}

	fmt.Fprintf(&out, "#endif\n")
	fmt.Print(out.String())
}

func mustAddr(s string) netip.Addr {
	return netip.MustParseAddr(s)
}
